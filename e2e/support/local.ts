/**
 * The Phase 3 end-to-end harness.
 *
 * Everything here targets the LOCAL Supabase stack started by `npx supabase start` — the same rule
 * `supabase/tests/node/helpers.mts` lives by, enforced the same way: a non-local URL throws at
 * module load rather than at some later assertion. No remote project, no production credential and
 * no real address is ever touched; every synthetic identity lives on `@teste.local`.
 *
 * Three capabilities are needed to prove the sign-in boundary for real:
 *
 *   1. **Identities** — created through the Auth Admin API with the secret key, which is the only
 *      path that creates an administrator (public sign-up is off, and `shouldCreateUser: false`
 *      keeps it off in code). Authorization rows go straight into `public.admin_users` over
 *      PostgreSQL, because the application never writes that table outside the Phase 6 RPCs.
 *   2. **The real one-time code** — read out of the local mail catcher (Mailpit, port 54324), not
 *      generated by the test. The code that arrives in the mailbox is the code the browser types.
 *   3. **The database's own view** — so a test can assert what the *server* knows (an e-mail was or
 *      was not sent; a row was or was not created) while asserting that the *application* reveals
 *      none of it.
 */
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { expect, type Page } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';
import pg from 'pg';

const { Client } = pg;

/** Every synthetic identity uses this domain, and cleanup keys off it. */
export const TEST_EMAIL_DOMAIN = 'teste.local';

const DEFAULT_DB_URL = 'postgresql://postgres:postgres@127.0.0.1:54322/postgres';
const DEFAULT_MAIL_URL = 'http://127.0.0.1:54324';

function readEnvFile(): Record<string, string> {
  const raw = readFileSync(resolve(process.cwd(), '.env.local'), 'utf8');
  const values: Record<string, string> = {};

  for (const line of raw.split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) values[match[1]] = match[2].trim();
  }

  return values;
}

const file = readEnvFile();

function required(name: string): string {
  const value = process.env[name] ?? file[name];
  if (!value) throw new Error(`${name} is not set in the environment or in .env.local.`);
  return value;
}

function assertLocal(label: string, url: string): string {
  if (!/^(postgresql|https?):\/\/(?:[^@/]*@)?(127\.0\.0\.1|localhost)(:|\/|$)/.test(url)) {
    throw new Error(`Refusing to run: ${label} (${url}) is not a local address.`);
  }
  return url;
}

export const LOCAL = {
  /** The application under test. Matches `NEXT_PUBLIC_SITE_URL` and Supabase's `site_url`. */
  siteUrl: assertLocal('NEXT_PUBLIC_SITE_URL', required('NEXT_PUBLIC_SITE_URL')),
  supabaseUrl: assertLocal('NEXT_PUBLIC_SUPABASE_URL', required('NEXT_PUBLIC_SUPABASE_URL')),
  /** Used ONLY by the harness, to act as the Auth Admin API. Never asserted against a bundle. */
  secretKey: required('SUPABASE_SECRET_KEY'),
  dbUrl: assertLocal('SUPABASE_DB_URL', process.env.SUPABASE_DB_URL ?? DEFAULT_DB_URL),
  mailUrl: assertLocal('SUPABASE_MAIL_URL', process.env.SUPABASE_MAIL_URL ?? DEFAULT_MAIL_URL),
} as const;

/* ------------------------------------------------------------------------------------------------
 * PostgreSQL
 * ---------------------------------------------------------------------------------------------- */

export async function withDb<T>(fn: (db: pg.Client) => Promise<T>): Promise<T> {
  const db = new Client({ connectionString: LOCAL.dbUrl });
  await db.connect();
  try {
    return await fn(db);
  } finally {
    await db.end();
  }
}

/* ------------------------------------------------------------------------------------------------
 * Identities
 * ---------------------------------------------------------------------------------------------- */

/**
 * A synthetic address. The random part has a fixed length, so two addresses built with labels of
 * the same length are themselves the same length — which the enumeration suite depends on.
 */
export function testEmail(label: string): string {
  return `${label}-${randomUUID().replace(/-/g, '').slice(0, 8)}@${TEST_EMAIL_DOMAIN}`;
}

function authAdminClient() {
  return createClient(LOCAL.supabaseUrl, LOCAL.secretKey, {
    auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  });
}

/**
 * An authenticated identity with no authorization at all — no `admin_users` row. This is the
 * "signed in but not an administrator" case, and the only way to create it is the Auth Admin API,
 * because the sign-in form cannot create accounts.
 */
export async function createAuthUser(email: string): Promise<string> {
  const { data, error } = await authAdminClient().auth.admin.createUser({
    email,
    email_confirm: true,
  });

  if (error || !data.user) {
    throw new Error(`Could not create the local test user ${email}: ${error?.message ?? 'no user'}`);
  }

  return data.user.id;
}

/** The same identity, plus the `admin_users` row that is the actual authorization. */
export async function createActiveAdmin(
  email: string,
  displayName = 'Organizador de teste',
): Promise<string> {
  const userId = await createAuthUser(email);

  await withDb((db) =>
    db.query(
      `insert into public.admin_users (user_id, email, display_name, is_active)
       values ($1, $2, $3, true)`,
      [userId, email, displayName],
    ),
  );

  return userId;
}

export async function deactivateAdmin(userId: string): Promise<void> {
  const result = await withDb((db) =>
    db.query('update public.admin_users set is_active = false where user_id = $1', [userId]),
  );

  expect(result.rowCount, 'the administrator row must exist before it is deactivated').toBe(1);
}

/** Total identities, or the identities for one address. Both forms are used by the enumeration suite. */
export async function countAuthUsers(email?: string): Promise<number> {
  const rows = await withDb((db) =>
    email
      ? db.query<{ total: string }>('select count(*)::text as total from auth.users where email = $1', [
          email,
        ])
      : db.query<{ total: string }>('select count(*)::text as total from auth.users'),
  );

  return Number(rows.rows[0].total);
}

/**
 * Removes every synthetic identity. The pgTAP suite asserts global counts — `11-seed.sql` requires
 * `public.admin_users` to be empty — so leftovers here would fail a suite that is not even running.
 * Audit rows go first: `admin_actions.actor_user_id` is ON DELETE SET NULL, so deleting the users
 * first would orphan them.
 */
export async function deleteTestIdentities(): Promise<void> {
  await withDb(async (db) => {
    await db.query(
      `delete from public.admin_actions
        where actor_user_id in (select id from auth.users where email like $1)`,
      [`%@${TEST_EMAIL_DOMAIN}`],
    );
    // public.admin_users.user_id is ON DELETE CASCADE, so this clears both tables.
    await db.query('delete from auth.users where email like $1', [`%@${TEST_EMAIL_DOMAIN}`]);
  });
}

/* ------------------------------------------------------------------------------------------------
 * The local mail catcher
 * ---------------------------------------------------------------------------------------------- */

interface MailSummary {
  ID: string;
  Created: string;
  To?: { Address: string }[];
}

async function mailJson<T>(path: string): Promise<T> {
  const response = await fetch(`${LOCAL.mailUrl}${path}`);

  if (!response.ok) {
    throw new Error(
      `The local mail catcher answered ${response.status} for ${path}. Is the stack running?`,
    );
  }

  return (await response.json()) as T;
}

async function messagesFor(email: string): Promise<MailSummary[]> {
  const { messages } = await mailJson<{ messages: MailSummary[] }>('/api/v1/messages?limit=200');

  return (messages ?? [])
    .filter((message) =>
      (message.To ?? []).some((to) => to.Address.toLowerCase() === email.toLowerCase()),
    )
    .sort((a, b) => Date.parse(b.Created) - Date.parse(a.Created));
}

/** How many sign-in e-mails an address actually received — the truth the application must not tell. */
export async function mailCountFor(email: string): Promise<number> {
  return (await messagesFor(email)).length;
}

export async function purgeMail(): Promise<void> {
  const response = await fetch(`${LOCAL.mailUrl}/api/v1/messages`, { method: 'DELETE' });
  if (!response.ok) throw new Error(`Could not clear the local mailbox: ${response.status}`);
}

/**
 * The six-digit code that actually arrived, read out of the message body. Tags are stripped first,
 * so the digits inside the confirmation link's token hash cannot be mistaken for the code.
 */
export async function waitForOtp(email: string, timeoutMs = 30_000): Promise<string> {
  const deadline = Date.now() + timeoutMs;

  while (Date.now() < deadline) {
    const [latest] = await messagesFor(email);

    if (latest) {
      const message = await mailJson<{ Text?: string; HTML?: string }>(
        `/api/v1/message/${latest.ID}`,
      );
      const visible = `${message.Text ?? ''}\n${(message.HTML ?? '').replace(/<[^>]*>/g, ' ')}`;
      const code = /(?:^|\D)(\d{6})(?:\D|$)/.exec(visible);
      if (code) return code[1];
    }

    await new Promise((wake) => setTimeout(wake, 250));
  }

  throw new Error(`No sign-in e-mail for ${email} arrived at ${LOCAL.mailUrl} within ${timeoutMs}ms.`);
}

/* ------------------------------------------------------------------------------------------------
 * Driving the real sign-in screen
 * ---------------------------------------------------------------------------------------------- */

/** Step one: type the address and receive the "check your e-mail" screen. */
export async function requestCode(page: Page, email: string): Promise<void> {
  await page.getByLabel('E-mail').fill(email);
  await page.getByRole('button', { name: 'Enviar código' }).click();
  await expect(page.getByRole('heading', { name: 'Verifique seu e-mail' })).toBeVisible();
}

/**
 * The whole flow, with the real code from the real mailbox. Deliberately stops at the click: where
 * the visitor lands afterwards is what each test is asserting.
 */
export async function signIn(page: Page, email: string, startAt = '/admin/entrar'): Promise<void> {
  await page.goto(startAt);
  await requestCode(page, email);

  const code = await waitForOtp(email);

  await page.getByLabel('Código').fill(code);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
}

/** The session cookies `@supabase/ssr` writes, chunked or not. */
export async function authCookies(page: Page) {
  return (await page.context().cookies()).filter((cookie) => /^sb-.*auth-token/.test(cookie.name));
}
